"""Inference service for Aussie EcoGuard, deployed on GCP Cloud Run.

POST /infer   {"url": "<presigned S3 GET URL>", "file_type": "image" | "video"}
           -> {"tags": {"fox": 2, "cat": 1}, "attributes": ["orange"], "model": "<model_label>"}
              Needs "Authorization: Bearer <Cognito access token>" with the scope
              aussie-ecoguard/infer, from a trusted user pool (see require_infer_token).
GET  /health  -> {"status": "ok", "model": "<model_label>"}   (no token needed)
GET  /docs    -> interactive API docs, generated by FastAPI from the types below

The models (MegaDetector -> SpeciesNet -> CLIP, see model.py) are loaded once
at startup from a folder holding config.json and the weights. On Cloud Run that
folder is downloaded first from MODEL_GCS (one model version in Cloud Storage);
locally MODEL_DIR points at it.

Videos (Spec 4.2): one frame every FRAME_EVERY seconds goes through the same
pipeline, and each species keeps its highest count over the frames (the same
animal is in many frames, so adding them up would count it again and again).
"""

import io
import os
import re
import shutil
import tempfile
import threading
import time
from contextlib import asynccontextmanager
from typing import Literal

import jwt
import requests
from fastapi import Depends, FastAPI, Header
from fastapi.responses import JSONResponse
from PIL import Image, ImageOps
from pydantic import BaseModel, Field

from model import Pipeline

# Where the model comes from. MODEL_GCS (e.g. gs://<bucket>/v1) is set on Cloud
# Run; the files are downloaded into LOCAL_MODEL_DIR at startup. Without it the
# models are read straight from MODEL_DIR (local development).
MODEL_GCS = os.environ.get("MODEL_GCS")
MODEL_DIR = os.environ.get("MODEL_DIR", "/models")
LOCAL_MODEL_DIR = "/tmp/models"
MAX_IMAGE_BYTES = 30 * 1024 * 1024  # camera-trap photos are a few MB
MAX_VIDEO_BYTES = 500 * 1024 * 1024  # the website's upload limit
FRAME_EVERY = 10  # seconds between the video frames that are checked (Spec 4.2)
# Longer videos are refused: 18 frames plus a cold start fit Cloud Run's 300 s timeout.
MAX_VIDEO_SECONDS = 180

# Only presigned URLs for our own media buckets are fetched. Otherwise a caller
# could make the service fetch any URL (SSRF).
ALLOWED_URL = r"^https://aussie-ecoguard-media-\d{12}\.s3(\.[a-z0-9-]+)?\.amazonaws\.com/uploads/"

# Cognito user pools whose tokens are accepted, comma-separated IDs such as
# "us-east-1_p3TKseWRr,us-east-1_AbCdEfGhI" (one per teammate's deployment).
# "*" accepts any Cognito pool: only for a short changeover, because anyone can
# create a pool with an aussie-ecoguard/infer scope and sign valid tokens.
TRUSTED_USER_POOLS = [p.strip() for p in os.environ.get("TRUSTED_USER_POOLS", "").split(",") if p.strip()]
INFER_SCOPE = "aussie-ecoguard/infer"
# Cognito's issuer URL: https://cognito-idp.<region>.amazonaws.com/<region>_<id>
COGNITO_ISSUER = re.compile(r"^https://cognito-idp\.([a-z0-9-]+)\.amazonaws\.com/(\1_[0-9A-Za-z]+)$")

pipeline = None  # loaded at startup; tests put a fake one here instead

# One image at a time: the models use all the CPU and memory of the instance
# (Cloud Run also runs with --concurrency 1, so this matters for local runs).
inference_lock = threading.Lock()


@asynccontextmanager
async def lifespan(app):
    global pipeline
    if pipeline is None:
        pipeline = load_pipeline()
    yield


def load_pipeline():
    if not MODEL_GCS:
        return timed(f"Loaded models from {MODEL_DIR}", Pipeline, MODEL_DIR)

    timed(f"Downloaded {MODEL_GCS}", download_models, MODEL_GCS, LOCAL_MODEL_DIR)
    loaded = timed("Loaded models", Pipeline, LOCAL_MODEL_DIR)
    # The weights are in memory now. Cloud Run's /tmp is also memory, so the
    # downloaded files would take another ~1 GB if they stayed.
    shutil.rmtree(LOCAL_MODEL_DIR)
    return loaded


def timed(message, func, *args):
    start = time.monotonic()
    result = func(*args)
    print(f"{message} in {time.monotonic() - start:.1f} s", flush=True)
    return result


def download_models(gcs_uri, dest):
    """Copy every object under gs://<bucket>/<prefix>/ into dest, keeping the
    folder layout. Big files are downloaded in 32 MB chunks in parallel, which
    is much faster than reading them through a Cloud Storage FUSE mount."""
    # Imported here so that local runs and the unit tests do not need it.
    from google.cloud import storage
    from google.cloud.storage import transfer_manager

    bucket_name, _, prefix = gcs_uri.removeprefix("gs://").partition("/")
    prefix = prefix.rstrip("/") + "/"
    # On Cloud Run the client signs in as the service's own service account.
    bucket = storage.Client().bucket(bucket_name)
    blobs = list(bucket.list_blobs(prefix=prefix))
    if not blobs:
        raise RuntimeError(f"no model files under {gcs_uri}")
    for blob in blobs:
        path = os.path.join(dest, blob.name[len(prefix):])
        os.makedirs(os.path.dirname(path), exist_ok=True)
        # Threads, not the default processes: the work is waiting on the network.
        transfer_manager.download_chunks_concurrently(
            blob, path, worker_type=transfer_manager.THREAD, max_workers=8)


app = FastAPI(title="Aussie EcoGuard inference", lifespan=lifespan)


# FastAPI checks every request body against this model before infer() runs.
# A bad or missing field (or a body that is not JSON) gets 422 automatically.
class InferRequest(BaseModel):
    url: str = Field(pattern=ALLOWED_URL, description="Presigned S3 GET URL for uploads/<sha256>")
    file_type: Literal["image", "video"]


class InferResponse(BaseModel):
    tags: dict[str, int]
    attributes: list[str]
    model: str


class FileTooLarge(Exception):
    pass


class BadImage(Exception):
    pass


class BadVideo(Exception):
    pass


class VideoTooLong(Exception):
    pass


# ---------- Cognito token check ----------

class AuthError(Exception):
    """Refuses the request with `status` and {"error": message}."""

    def __init__(self, status, message):
        super().__init__(message)
        self.status = status


@app.exception_handler(AuthError)
def auth_error(request, exc):
    return JSONResponse({"error": str(exc)}, exc.status)


_jwks_clients = {}


def jwks_client(issuer):
    """The public keys of one user pool. PyJWKClient downloads them once and caches them."""
    if issuer not in _jwks_clients:
        _jwks_clients[issuer] = jwt.PyJWKClient(f"{issuer}/.well-known/jwks.json")
    return _jwks_clients[issuer]


def trusted_issuer(issuer):
    match = COGNITO_ISSUER.match(issuer or "")
    return bool(match) and ("*" in TRUSTED_USER_POOLS or match.group(2) in TRUSTED_USER_POOLS)


def require_infer_token(authorization: str | None = Header(default=None)):
    """Lets the request through only with a Cognito access token that is
    signed by a trusted user pool, not expired, and carries the infer scope.

    The tagging Lambda gets such a token as the machine client
    aussie-ecoguard-tagging (infra/terraform/aws/cognito.tf). Users of the same
    pool also hold tokens signed by it (sign-up is open), but none of theirs
    carries the scope.
    """
    if not authorization or not authorization.startswith("Bearer "):
        raise AuthError(401, "missing bearer token")
    token = authorization.removeprefix("Bearer ")
    try:
        # Read `iss` without checking anything yet, only to pick the pool. The
        # list of trusted pools decides; the keys are never fetched from an
        # address the token chose.
        issuer = jwt.decode(token, options={"verify_signature": False}).get("iss")
        if not trusted_issuer(issuer):
            raise AuthError(401, "token is not from a trusted user pool")
        key = jwks_client(issuer).get_signing_key_from_jwt(token).key
        # Now the real check: signature (RS256 only), issuer and expiry.
        # Access tokens have no `aud`; token_use and scope below say what the token is for.
        claims = jwt.decode(
            token, key, algorithms=["RS256"], issuer=issuer,
            options={"require": ["exp", "iss"], "verify_aud": False},
        )
    except jwt.PyJWKClientConnectionError:
        raise AuthError(503, "could not fetch the user pool's keys")  # the Lambda retries 5xx
    except jwt.PyJWTError:
        raise AuthError(401, "invalid token")

    if claims.get("token_use") != "access" or INFER_SCOPE not in claims.get("scope", "").split():
        raise AuthError(403, f"token lacks the {INFER_SCOPE} scope")


@app.get("/health")
def health():
    return {"status": "ok", "model": pipeline.config["model_label"]}


# A plain `def` (not `async def`): FastAPI runs it in a thread pool, so the
# blocking download and the models do not stall the event loop.
# Errors use {"error": ...}, which the tagging Lambda stores in META. It treats
# 4xx (except 429) as permanent (status FAILED at once) and 5xx as temporary
# (SQS retries the message).
@app.post("/infer", response_model=InferResponse, dependencies=[Depends(require_infer_token)])
def infer(req: InferRequest):
    limit = MAX_VIDEO_BYTES if req.file_type == "video" else MAX_IMAGE_BYTES
    # Never echo download exceptions: their text contains the presigned URL and token.
    try:
        if req.file_type == "video":
            tags, attributes = infer_video(req.url)
        else:
            tags, attributes = infer_image(req.url)
    except FileTooLarge:
        return JSONResponse({"error": f"file is larger than {limit // 2**20} MB"}, 413)
    except requests.HTTPError as e:
        # e.g. the presigned URL or the credentials that signed it expired
        return JSONResponse(
            {"error": f"could not download file (S3 returned {e.response.status_code})"}, 502
        )
    except requests.RequestException:
        return JSONResponse({"error": "could not download file"}, 502)
    except BadImage:
        return JSONResponse({"error": "file is not a valid image"}, 422)
    except BadVideo:
        return JSONResponse({"error": "file is not a valid video"}, 422)
    except VideoTooLong as e:
        return JSONResponse(
            {"error": f"video is {e.args[0]:.0f} s long; the limit is {MAX_VIDEO_SECONDS // 60} minutes"}, 422
        )
    return {"tags": tags, "attributes": attributes, "model": pipeline.config["model_label"]}


def infer_image(url):
    buffer = io.BytesIO()
    download(url, buffer, MAX_IMAGE_BYTES)
    try:
        image = open_image(buffer.getvalue())
    except (Image.UnidentifiedImageError, Image.DecompressionBombError, OSError) as e:
        raise BadImage() from e
    with inference_lock:
        return pipeline.detect(image)


def infer_video(url):
    # A file on local disk, not a URL: OpenCV seeks around in the video, and the
    # presigned URL could expire before the last frame. Cloud Run's /tmp is
    # memory, which is why the instance has room to spare (8 GiB).
    with tempfile.TemporaryDirectory() as folder:
        path = os.path.join(folder, "video")
        with open(path, "wb") as f:
            download(url, f, MAX_VIDEO_BYTES)
        frames = read_frames(path)
    with inference_lock:
        results = [pipeline.detect(frame) for frame in frames]
    return merge_frames(results)


def download(url, out, limit):
    """Stream the file into `out` (a binary file object), giving up past `limit` bytes."""
    size = 0
    with requests.get(url, stream=True, timeout=(5, 30)) as response:
        response.raise_for_status()
        for chunk in response.iter_content(chunk_size=1024 * 1024):
            size += len(chunk)
            if size > limit:
                raise FileTooLarge()
            out.write(chunk)


def open_image(data):
    """Bytes -> upright RGB PIL image. The format comes from the file's own
    header, so the extension-less S3 key does not matter."""
    image = Image.open(io.BytesIO(data))
    image = ImageOps.exif_transpose(image)  # phone photos store rotation in EXIF
    return image.convert("RGB")


def read_frames(path):
    """One upright RGB PIL image every FRAME_EVERY seconds of the video at path.

    OpenCV (with FFmpeg) reads mp4 and mov, H.264 and HEVC, and by default turns
    phone videos filmed in portrait upright using their rotation metadata.
    """
    import cv2  # imported here so the unit tests do not need OpenCV

    video = cv2.VideoCapture(path)
    try:
        fps = video.get(cv2.CAP_PROP_FPS)
        frame_count = video.get(cv2.CAP_PROP_FRAME_COUNT)
        if not video.isOpened() or fps <= 0 or frame_count <= 0:
            raise BadVideo()
        duration = frame_count / fps
        if duration > MAX_VIDEO_SECONDS:
            raise VideoTooLong(duration)
        frames = []
        for t in frame_times(duration):
            video.set(cv2.CAP_PROP_POS_MSEC, t * 1000)
            ok, frame = video.read()
            if ok:  # skip a frame that cannot be decoded rather than fail the video
                frames.append(Image.fromarray(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)))
    finally:
        video.release()
    if not frames:
        raise BadVideo()
    return frames


def frame_times(duration):
    """Seconds of the frames to check: 0, 10, 20, ... while still inside the video."""
    return [t for t in range(0, int(duration) + 1, FRAME_EVERY) if t < duration]


def merge_frames(results):
    """[(tags, attributes) per frame] -> one (tags, attributes) for the video.

    Each species keeps its highest count in any single frame: two foxes that
    walk through ten frames are still two foxes. Colours are listed once,
    most frequent first.
    """
    tags, colours = {}, {}
    for frame_tags, frame_attributes in results:
        for species, count in frame_tags.items():
            tags[species] = max(tags.get(species, 0), count)
        for colour in frame_attributes:
            colours[colour] = colours.get(colour, 0) + 1
    return tags, sorted(colours, key=colours.get, reverse=True)
